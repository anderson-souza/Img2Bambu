"""PreToolUse gate: block destructive shell commands and edits to build artifacts.

Exit 2 blocks the tool call; stderr is shown to Claude as the reason.
"""
import json
import re
import sys

BLOCKED_COMMANDS = [
    (r"\brm\s+(-\w*r\w*f\w*|-\w*f\w*r\w*|-r\s+-f|-f\s+-r)\s+(/|~|\$HOME|\.\.?|\*)(\s|/?$|;|&)",
     "rm -rf on /, ~, ., .. or * is not allowed; remove specific paths instead"),
    (r"\bgit\s+push\b.*(\s--force(?!-with-lease)\b|\s-f\b)",
     "force push is not allowed; use --force-with-lease if needed"),
    (r"\bgit\s+reset\s+--hard\b", "git reset --hard discards work; commit or ask the user first"),
    (r"\bgit\s+clean\s+-\w*f", "git clean -f deletes untracked files; ask the user first"),
]
# why: build/ and dist/ are PyInstaller output, regenerated by img2bambu.spec
ARTIFACT_DIRS = re.compile(r"(^|[\\/])(build|dist)[\\/]")


def check(event):
    tool = event.get("tool_name", "")
    args = event.get("tool_input", {}) or {}
    if tool == "Bash":
        cmd = args.get("command", "")
        for pattern, reason in BLOCKED_COMMANDS:
            if re.search(pattern, cmd):
                return reason
    elif tool in ("Edit", "Write", "NotebookEdit"):
        path = args.get("file_path") or args.get("notebook_path") or ""
        rel = path.replace(event.get("cwd", ""), "", 1)
        if ARTIFACT_DIRS.search(rel):
            return f"{path} is a build artifact; change the source or img2bambu.spec instead"
    return None


def main():
    try:
        event = json.load(sys.stdin)
    except ValueError as e:
        # hazard: fails open on malformed input so a hook bug never wedges the session
        print(f"guard.py: could not parse hook input ({e}); allowing", file=sys.stderr)
        return 0
    reason = check(event)
    if reason:
        print(f"Blocked by .claude/hooks/guard.py: {reason}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
